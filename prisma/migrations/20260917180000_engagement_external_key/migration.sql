-- ============================================================================
--  Внешний ключ заявки
--
--  Техническое задание требует принимать данные внешних систем «с
--  последующим добавлением в существующий или новый workflow». Выполнялась
--  только вторая половина: каждое событие LMS или сайта заводило новую
--  заявку, и завершение обучения по человеку, обратившемуся через сайт,
--  создавало вторую заявку вместо продвижения первой.
--
--  Пара «внешняя система + идентификатор обращения» уникальна, поэтому
--  повторные события находят заявку, а не плодят её. NULL в паре ничему
--  не мешает: у заявок, заведённых руками, внешнего ключа нет вовсе.
-- ============================================================================

-- AlterTable
ALTER TABLE "engagement" ADD COLUMN     "external_id" TEXT,
ADD COLUMN     "external_source" TEXT;

-- CreateIndex
CREATE UNIQUE INDEX "engagement_external_source_external_id_key" ON "engagement"("external_source", "external_id");
