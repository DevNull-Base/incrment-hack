-- ============================================================================
--  Жизненный цикл персональных данных (152-ФЗ)
--
--  Добавляет два недостающих для правомерной обработки атрибута:
--   • правовое основание (ст. 6) — оператор обязан предъявить его по запросу;
--   • отметку об обезличивании (ст. 21) — подтверждает исполнение требования
--     субъекта либо истечение срока хранения (ч. 7 ст. 5).
--
--  Существующие записи получают основание UNDEFINED: это НЕ основание,
--  а признак того, что инвентаризация по ним не завершена. Проставить
--  фактическое основание обязан ответственный за организацию обработки ПДн.
-- ============================================================================

-- CreateEnum
CREATE TYPE "PdLawfulBasis" AS ENUM ('CONTRACT', 'CONSENT', 'LEGAL_OBLIGATION', 'UNDEFINED');

-- AlterTable
ALTER TABLE "person" ADD COLUMN     "erased_at" TIMESTAMP(3),
ADD COLUMN     "erasure_reason" TEXT,
ADD COLUMN     "lawful_basis" "PdLawfulBasis" NOT NULL DEFAULT 'UNDEFINED';

-- CreateIndex
CREATE INDEX "person_erased_at_idx" ON "person"("erased_at");

-- ============================================================================
--  Правила ограничения видимости: тип значений
--
--  Измерение REGION хранит названия регионов, а не идентификаторы, — у них
--  нет собственной таблицы. Колонка при этом была объявлена как uuid[],
--  поэтому правило по региону записать было невозможно: PostgreSQL отвергал
--  значение, и ограничение видимости по региону не действовало.
-- ============================================================================

-- AlterTable
ALTER TABLE "data_scope_rule" ALTER COLUMN "allowed_ids" SET DATA TYPE TEXT[];
