-- ============================================================================
--  Роль, назначенная администратором, не перекрывается токеном
--
--  Смена роли в CRM откатывалась на первом же запросе пользователя: сброс
--  кэша профиля заставлял заново прочитать роль из токена Keycloak. Понизить
--  права скомпрометированной учётной записи через систему было невозможно.
--  Признак отмечает роль, назначенную администратором в CRM: такая роль
--  больше не синхронизируется из токена.
-- ============================================================================

-- AlterTable
ALTER TABLE "app_user" ADD COLUMN     "role_managed_locally" BOOLEAN NOT NULL DEFAULT false;
