/** Ширина колонок — чтобы файл открывался читаемым, а не «лесенкой». */
const WIDTHS = [58, 22, 30, 18, 22, 28, 20, 20, 42, 52];

async function writeXlsx(file) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'ИТ Школа РТК';
  workbook.created = new Date();

  const sheet = workbook.addWorksheet('Взаимодействия');
  sheet.columns = HEADERS.map((header, index) => ({ header, width: WIDTHS[index] }));
  sheet.getRow(1).font = { bold: true };
  sheet.getRow(1).alignment = { vertical: 'middle', wrapText: true };
  sheet.views = [{ state: 'frozen', ySplit: 1 }];

  for (const row of ROWS) {
    sheet.addRow(row);
  }

  await workbook.xlsx.writeFile(file);
}

function writeXls(file) {
  // BIFF8 — формат Excel 97-2003. Пишется как есть, без обёртки в xlsx:
  // именно такой файл и приходит из старых выгрузок заказчика.
  const sheet = XLSX.utils.aoa_to_sheet([HEADERS, ...ROWS]);
  sheet['!cols'] = WIDTHS.map((width) => ({ wch: width }));

  const book = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(book, sheet, 'Взаимодействия');

  // Запись через буфер, а не XLSX.writeFile: в ESM-сборке SheetJS файловый
  // модуль не подключён, и прямая запись на диск падает.
  writeFileSync(file, XLSX.write(book, { type: 'buffer', bookType: 'biff8' }));
}

