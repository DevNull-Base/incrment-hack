/** Собирает файл в память — используется проверками напрямую. */
export async function buildSampleBuffer(runId = '') {
  const workbook = new ExcelJS.Workbook();
  const sheet = workbook.addWorksheet('Выгрузка');

  sheet.addRow([
    'ВУЗ', 'Производитель', 'Программное обеспечение', 'No договора',
    'Дата подписания', 'Срок действия', 'Статус передачи', 'Менеджер',
    'Контактное лицо', 'Примечание', 'Внутренний код отдела',
  ]);

  for (const row of buildRows(runId)) {
    sheet.addRow([...row, 'ОТД-' + Math.floor(Math.random() * 900 + 100)]);
  }

  return Buffer.from(await workbook.xlsx.writeBuffer());
}

