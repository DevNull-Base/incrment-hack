/**
 * Метка прогона в наименованиях новых вузов.
 *
 * Нужна, чтобы проверка была повторяемой: без неё второй запуск находил бы
 * вузы, созданные первым, и ожидания «будет создано 2» не выполнялись бы.
 * Проверяется поведение системы, а не порядок запуска тестов.
 */
export function buildRows(runId = '') {
  const mark = runId ? ` ${runId}` : '';
  return ROWS.map((row) => [...row]).map((row) => {
    if (row[0].startsWith('Мурманский') || row[0].startsWith('Псковский')) {
      row[0] = `${row[0]}${mark}`;
    }
    return row;
  });
}

