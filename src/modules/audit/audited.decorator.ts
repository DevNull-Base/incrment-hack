import { SetMetadata } from '@nestjs/common';
import type { AuditAction } from './audit.service.js';

export const AUDITED_KEY = 'auditedAction';

export interface AuditedOptions {
  /** Действие из закрытого перечня AUDIT_ACTIONS. */
  action: AuditAction;
  /** Тип объекта, попадающий в журнал: University, Vendor, ItDirection и т.д. */
  entityType: string;
}

/**
 * Помечает изменяющий маршрут как подлежащий протоколированию.
 *
 * Альтернатива — вызывать журналирование внутри каждого сервиса. Для
 * каталогов это означало бы протащить текущего пользователя через полтора
 * десятка методов, которые в нём иначе не нуждаются, и превратить
 * справочные сервисы в зависимые от контекста аутентификации.
 *
 * Ограничение подхода: интерцептор видит результат операции, но не
 * предшествующее состояние, поэтому beforeState для таких событий пуст.
 * Для справочников этого достаточно — история изменений восстанавливается
 * по последовательности записей. Там, где важно именно «было → стало»
 * (роли, права, персональные данные), журналирование выполняется в сервисе
 * явно, с обоими состояниями.
 */
export const Audited = (options: AuditedOptions) => SetMetadata(AUDITED_KEY, options);
