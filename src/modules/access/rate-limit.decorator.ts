import { SetMetadata } from '@nestjs/common';

export const RATE_LIMIT_KEY = 'rateLimit';
export const RATE_LIMIT_SKIP_KEY = 'rateLimitSkip';

export interface RateLimitOptions {
  /** Сколько запросов допускается в окне. */
  limit?: number;
  /** Длительность окна в секундах. */
  ttlSec?: number;
  /**
   * Имя корзины счётчиков. Маршруты с одним именем расходуют общий лимит.
   * Так «сформировать отчёт» и «скачать отчёт» ограничиваются вместе:
   * разделение позволило бы выгружать данные вдвое быстрее установленного.
   */
  bucket?: string;
  /** Брать лимит из настройки THROTTLE_EXPORT_LIMIT вместо общей. */
  export?: boolean;
}

/**
 * Ограничение частоты обращений для маршрута.
 *
 * Общий лимит применяется ко всем маршрутам по умолчанию; декоратор нужен
 * там, где требуется более строгий порог, — выгрузки, импорт, скачивание
 * файлов. Именно эти методы позволяют вынести значительный объём данных,
 * включая персональные, не нарушая при этом никаких прав доступа.
 */
export const RateLimit = (options: RateLimitOptions) => SetMetadata(RATE_LIMIT_KEY, options);

/**
 * Снимает ограничение с маршрута.
 * Применяется к служебным пробам, которые опрашиваются оркестратором
 * с высокой частотой и данных не выдают.
 */
export const SkipRateLimit = () => SetMetadata(RATE_LIMIT_SKIP_KEY, true);
