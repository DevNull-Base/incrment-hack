import { SetMetadata } from '@nestjs/common';

export const IS_PUBLIC_KEY = 'isPublic';

/**
 * Помечает маршрут как доступный без аутентификации.
 *
 * Модель безопасности «по умолчанию закрыто»: глобальный guard требует
 * валидный токен для всех маршрутов, и только явно помеченные этим
 * декоратором остаются открытыми (health-пробы, метрики, Swagger).
 * Добавление нового контроллера не может случайно открыть доступ к данным.
 */
export const Public = () => SetMetadata(IS_PUBLIC_KEY, true);
