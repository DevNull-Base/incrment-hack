/**
 * Нормализация наименований для поиска дубликатов.
 *
 * Задача прикладная, а не абстрактная: в присылаемых заказчиком таблицах
 * один и тот же вуз записан по-разному — «МГТУ им. Баумана»,
 * «МГТУ им. Н.Э. Баумана», «Московский государственный технический
 * университет имени Н.Э.Баумана». Без приведения к общему виду импорт
 * плодил бы дубликаты, а отчёты считали бы один вуз за несколько.
 *
 * Нормализованная форма хранится в university.normalized_name и участвует
 * в триграммном сравнении (pg_trgm) вместе с исходным наименованием.
 */

/**
 * Символы-разделители, которые заменяются пробелом.
 *
 * Намеренно задан набором, а не классом регулярного выражения: в классе
 * дефис рядом с другими символами легко превращается в оператор диапазона
 * и незаметно захватывает целые алфавиты. Набор от этого свободен.
 */
const SEPARATOR_CHARS = new Set([
  '.', ',', ';', ':', '(', ')', '[', ']', '{', '}', '/',
  // Обратная косая черта задаётся кодом символа: литерал обратного слэша
  // в исходном коде — источник трудноуловимых ошибок экранирования.
  String.fromCharCode(92),
  '-', '–', '—', '_',
  '«', '»', '"', "'", '`', '‘', '’', '“', '”',
]);

/** Сокращения, приводимые к развёрнутой форме или удаляемые. */
const ABBREVIATION_MAP: ReadonlyMap<string, string> = new Map([
  ['им', 'имени'],
  ['фгбоу', ''],
  ['фгаоу', ''],
  ['фгбну', ''],
  ['гаоу', ''],
  ['боу', ''],
  ['во', ''],
  ['впо', ''],
  ['ниу', ''],
]);

/** Служебные слова, не несущие различающего смысла. */
const STOP_WORDS = new Set([
  'университет',
  'государственный',
  'национальный',
  'исследовательский',
  'федеральный',
  'высшего',
  'образования',
  'учреждение',
  'бюджетное',
  'автономное',
  'образовательное',
  'имени',
]);

/**
 * Приводит наименование к каноническому виду: нижний регистр, без пунктуации,
 * кавычек, повторных пробелов и организационно-правовых префиксов.
 */
export function normalizeName(raw: string): string {
  // Ё и е в наименованиях вузов пишут вперемешку.
  const lowered = raw.toLowerCase().replace(/ё/g, 'е');

  // Разделители заменяем пробелом посимвольно — без регулярных выражений.
  let cleaned = '';
  for (const char of lowered) {
    cleaned += SEPARATOR_CHARS.has(char) ? ' ' : char;
  }

  const tokens = cleaned
    .split(' ')
    .map((token) => token.trim())
    .filter((token) => token.length > 0)
    .map((token) => ABBREVIATION_MAP.get(token) ?? token)
    .filter((token) => token.length > 0);

  return tokens.join(' ');
}

/**
 * Значимые токены наименования — без служебных слов.
 * Используется для оценки схожести, когда триграммного сравнения мало.
 */
export function significantTokens(raw: string): string[] {
  return normalizeName(raw)
    .split(' ')
    .filter((token) => token.length > 1 && !STOP_WORDS.has(token));
}

/**
 * Грубая оценка схожести двух наименований по коэффициенту Жаккара
 * на множестве значимых токенов: 0 — ничего общего, 1 — совпадение.
 *
 * Дополняет pg_trgm: триграммы хорошо ловят опечатки, а токены —
 * случай, когда одно наименование является сокращением другого.
 */
export function nameSimilarity(left: string, right: string): number {
  const a = new Set(significantTokens(left));
  const b = new Set(significantTokens(right));

  if (a.size === 0 || b.size === 0) {
    return 0;
  }

  let intersection = 0;
  for (const token of a) {
    if (b.has(token)) intersection++;
  }

  return intersection / (a.size + b.size - intersection);
}
